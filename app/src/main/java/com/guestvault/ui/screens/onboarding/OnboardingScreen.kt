@HiltViewModel
class OnboardingViewModel @Inject constructor(
    private val settingsRepository: SettingsRepository,
    private val applyRecommendedDefaults: ApplyRecommendedDefaultsUseCase,
    observeSettings: ObserveSettingsUseCase
) : ViewModel() {

    val themeMode: StateFlow<ThemeMode> = observeSettings()
        .map { it.themeMode }
        .stateIn(viewModelScope, SharingStarted.WhileSubscribed(5_000), ThemeMode.SYSTEM)

    private val _completed = MutableStateFlow(false)
    val completed: StateFlow<Boolean> = _completed

    fun complete() {
        if (_completed.value) return
        viewModelScope.launch {
            applyRecommendedDefaults()
            settingsRepository.setOnboardingCompleted(true)
            _completed.value = true
        }
    }
}

@Composable
fun OnboardingRoute(
    onFinished: () -> Unit,
    viewModel: OnboardingViewModel = hiltViewModel()
) {
    val completed by viewModel.completed.collectAsStateWithLifecycle()

    androidx.compose.runtime.LaunchedEffect(completed) {
        if (completed) onFinished()
    }

    OnboardingScreen(onGetStarted = viewModel::complete)
}

@Composable
fun OnboardingScreen(
    onGetStarted: () -> Unit,
    modifier: Modifier = Modifier
) {
    val pagerState = rememberPagerState(pageCount = { pages.size })
    val scope = rememberCoroutineScope()
    val lastPage = pagerState.currentPage == pages.lastIndex

    Scaffold(
        modifier = modifier,
        containerColor = MaterialTheme.colorScheme.background
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(horizontal = 24.dp)
        ) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 12.dp),
                verticalAlignment = Alignment.CenterVertically
            ) {
                GuestVaultMark(size = 36.dp)
                Spacer(Modifier.width(10.dp))
                Text(
                    text = "GuestVault",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onBackground
                )
                Spacer(Modifier.weight(1f))
                if (!lastPage) {
                    TextButton(onClick = onGetStarted) {
                        Text("Skip", color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }
            }

            HorizontalPager(
                state = pagerState,
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f)
            ) { index ->
                val page = pages[index]
                // Centred when it fits, scrollable when the font scale is large.
                Box(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(horizontal = 8.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Column(
                        modifier = Modifier
                            .verticalScroll(rememberScrollState())
                            .padding(vertical = 8.dp),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        PageAnimation(page = page)

                        Spacer(Modifier.height(28.dp))
                        Text(
                            text = page.title,
                            style = MaterialTheme.typography.headlineMedium,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onBackground,
                            textAlign = TextAlign.Center
                        )
                        Spacer(Modifier.height(14.dp))
                        Text(
                            text = page.message,
                            style = MaterialTheme.typography.bodyLarge,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            textAlign = TextAlign.Center,
                            lineHeight = MaterialTheme.typography.bodyLarge.lineHeight * 1.15f
                        )
                    }
                }
            }

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(vertical = 20.dp),
                horizontalArrangement = Arrangement.Center
            ) {
                repeat(pages.size) { index ->
                    val selected = pagerState.currentPage == index
                    val width by animateDpAsState(
                        targetValue = if (selected) 26.dp else 8.dp,
                        label = "indicatorWidth"
                    )
                    Box(
                        modifier = Modifier
                            .padding(horizontal = 4.dp)
                            .height(8.dp)
                            .width(width)
                            .clip(CircleShape)
                            .background(
                                if (selected) {
                                    MaterialTheme.colorScheme.primary
                                } else {
                                    MaterialTheme.colorScheme.outline.copy(alpha = 0.6f)
                                }
                            )
                    )
                }
            }

            PrimaryButton(
                text = if (lastPage) "Get Started" else "Next",
                onClick = {
                    if (lastPage) {
                        onGetStarted()
                    } else {
                        scope.launch {
                            pagerState.animateScrollToPage(pagerState.currentPage + 1)
                        }
                    }
                }
            )

            Text(
                text = "No account. No cloud. Everything stays on this phone.",
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 14.dp, bottom = 20.dp)
            )
        }
    }
}

/**
 * Plays the page's Lottie animation, or draws the static fallback.
 *
 * Two degradation paths, both deliberate:
 *  - the JSON fails to parse (a corrupted APK / an aggressive shrinker) →
 *    the original icon artwork, so the page still explains itself;
 *  - the owner turned off animations in accessibility settings → the final
 *    frame, which is the settled composition, not a blank first frame.
 */
@Composable
private fun PageAnimation(page: OnboardingPage) {
    val context = LocalContext.current
    val animationsDisabled = remember(context) {
        runCatching {
            Settings.Global.getFloat(
                context.contentResolver,
                Settings.Global.ANIMATOR_DURATION_SCALE,
                1f
            ) == 0f
        }.getOrDefault(false)
    }

    val compositionState = rememberLottieComposition(
        spec = LottieCompositionSpec.RawRes(page.animation)
    )
    val composition = compositionState.value

    if (composition == null) {
        // Fallback: the pre-Lottie artwork, unchanged.
        Box(
            modifier = Modifier
                .size(148.dp)
                .clip(CircleShape)
                .background(page.fallbackBrush)
                .semantics { contentDescription = page.animationDescription },
            contentAlignment = Alignment.Center
        ) {
            Icon(
                imageVector = page.fallbackIcon,
                contentDescription = null,
                tint = Color.White,
                modifier = Modifier.size(66.dp)
            )
        }
        return
    }

    // Lottie honours the system animation scale itself; the explicit override
    // exists so a reduced-motion user sees the finished frame instead of an
    // empty first frame.
    val animatedProgress = animateLottieCompositionAsState(
        composition = composition,
        restartOnPlay = true
    )
    val progress = if (animationsDisabled) 1f else animatedProgress.value

    LottieAnimation(
        composition = composition,
        progress = { progress },
        modifier = Modifier
            .size(232.dp)
            .semantics { contentDescription = page.animationDescription }
    )
}
