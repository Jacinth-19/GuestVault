/**
 * One onboarding page.
 *
 * [animation] is the Lottie file in `res/raw`; [fallbackIcon] is drawn instead
 * when the animation is missing or fails to parse, so a bad asset degrades to
 * the old static art instead of a blank hole. The animations are generated by
 * `scripts/assets/build_lottie.py` and validated in CI.
 */
private data class OnboardingPage(
    @RawRes val animation: Int,
    val fallbackIcon: ImageVector,
    val fallbackBrush: Brush,
    val title: String,
    val message: String,
    val animationDescription: String
)

private val pages = listOf(
    OnboardingPage(
        animation = R.raw.onboarding_lend,
        fallbackIcon = Icons.Rounded.Shield,
        fallbackBrush = HeroGradient,
        title = "Lend your phone safely",
        message = "Hand over your phone without handing over your life. " +
            "GuestVault creates a temporary space for whoever is borrowing it.",
        animationDescription = "A phone is handed over and a shield locks onto it"
    ),
    OnboardingPage(
        animation = R.raw.onboarding_apps,
        fallbackIcon = Icons.Rounded.Apps,
        fallbackBrush = TealGradient,
